fn expanded_feature_filter(
    requested: Option<&[String]>,
    regime_aware: bool,
) -> Option<Vec<String>> {
    let Some(requested) = requested else {
        return None;
    };
    let mut expanded = requested.to_vec();
    if regime_aware {
        for name in REGIME_INPUT_FEATURES {
            if !expanded.iter().any(|candidate| candidate == name) {
                expanded.push(name.to_string());
            }
        }
    }
    Some(expanded)
}

/// Add a small, explicitly specified regime representation from causal event
/// features. The thresholds are fixed constants, not fit from any future
/// labels. This makes the regime state reproducible in a live gate and gives
/// the model an explicit trend/chop/transition vocabulary instead of asking a
/// linear head to discover it from unrelated indicator scales.
fn append_regime_features(dataset: &mut Dataset) -> Result<()> {
    if dataset
        .feature_names
        .iter()
        .any(|name| REGIME_OUTPUT_FEATURES.contains(&name.as_str()))
    {
        bail!("regime features are already present in the event dataset");
    }
    let indices = REGIME_INPUT_FEATURES
        .iter()
        .map(|name| {
            dataset
                .feature_names
                .iter()
                .position(|candidate| candidate == name)
                .ok_or_else(|| {
                    anyhow::anyhow!(
                        "--regime-aware requires causal feature `{name}`; prepare the geometry/regime feature registry first"
                    )
                })
        })
        .collect::<Result<Vec<_>>>()?;
    let mut additions = Vec::with_capacity(dataset.rows.len());
    let mut previous_session: Option<&str> = None;
    let mut previous_trend_score = 0.0;
    let mut previous_chop_score = 0.0;
    let mut previous_bucket = "unclassified";
    let mut regime_age_events: f64 = 0.0;
    for row in &dataset.rows {
        let same_session = previous_session == Some(row.session_id.as_str());
        let value = |name_index: usize| row.raw_features[name_index];
        let adx_score = ((value(indices[1]) - 15.0) / 20.0).clamp(0.0, 1.0);
        let er = value(indices[2]).clamp(0.0, 1.0);
        let chop = (value(indices[3]) / 100.0).clamp(0.0, 1.0);
        let vhf = value(indices[4]).clamp(0.0, 1.0);
        let persistence = value(indices[5]).clamp(0.0, 1.0);
        let flip_rate = value(indices[6]).clamp(0.0, 1.0);
        let agreement = value(indices[7]).clamp(0.0, 1.0);
        let trend_score = (adx_score + er + (1.0 - chop) + vhf + persistence + agreement) / 6.0;
        let chop_score = ((1.0 - er) + chop + flip_rate + (1.0 - agreement)) / 4.0;
        let transition_score = (1.0 - (trend_score - chop_score).abs()).clamp(0.0, 1.0);
        let trend = (trend_score >= 0.55 && trend_score > chop_score + 0.10) as u8 as f64;
        let choppy = (chop_score >= 0.55 && chop_score > trend_score + 0.10) as u8 as f64;
        let transition = if trend == 0.0 && choppy == 0.0 {
            1.0
        } else {
            0.0
        };
        let direction = value(indices[0]);
        let direction_score = direction * (trend_score - chop_score);
        let bucket = regime_bucket_from_scores(trend_score, chop_score);
        let trend_delta = if same_session {
            trend_score - previous_trend_score
        } else {
            0.0
        };
        let chop_delta = if same_session {
            chop_score - previous_chop_score
        } else {
            0.0
        };
        let shift_score = if same_session {
            ((trend_score - chop_score) - (previous_trend_score - previous_chop_score))
                .abs()
                .clamp(0.0, 1.0)
        } else {
            0.0
        };
        let trend_shift = (trend_delta - chop_delta).max(0.0).clamp(0.0, 1.0);
        let chop_shift = (chop_delta - trend_delta).max(0.0).clamp(0.0, 1.0);
        let bucket_change = if same_session && bucket != previous_bucket {
            1.0
        } else {
            0.0
        };
        if !same_session || bucket_change > 0.0 {
            regime_age_events = 0.0;
        } else {
            regime_age_events = (regime_age_events + 1.0).min(120.0);
        }
        let values = vec![
            trend_score,
            chop_score,
            transition_score,
            trend,
            choppy,
            transition,
            direction_score,
            direction * trend,
            direction * choppy,
            direction * transition,
            trend_delta,
            chop_delta,
            shift_score,
            trend_shift,
            chop_shift,
            bucket_change,
            regime_age_events / 120.0,
        ];
        if values.iter().any(|value| !value.is_finite()) {
            bail!("regime feature calculation produced a non-finite value");
        }
        additions.push(values);
        previous_session = Some(row.session_id.as_str());
        previous_trend_score = trend_score;
        previous_chop_score = chop_score;
        previous_bucket = bucket;
    }
    for (row, values) in dataset.rows.iter_mut().zip(additions) {
        row.raw_features.extend(values);
    }
    dataset
        .feature_names
        .extend(REGIME_OUTPUT_FEATURES.into_iter().map(str::to_string));
    Ok(())
}

fn regime_bucket(feature_names: &[String], features: &[f64]) -> &'static str {
    if !feature_names
        .iter()
        .any(|candidate| candidate == "regime_trend_score")
    {
        return "unclassified";
    }
    let value = |name: &str| {
        feature_names
            .iter()
            .position(|candidate| candidate == name)
            .and_then(|index| features.get(index).copied())
            .unwrap_or(0.0)
    };
    regime_bucket_from_scores(value("regime_trend_score"), value("regime_chop_score"))
}

fn regime_bucket_from_scores(trend_score: f64, chop_score: f64) -> &'static str {
    if trend_score >= 0.55 && trend_score > chop_score + 0.10 {
        "trend"
    } else if chop_score >= 0.55 && chop_score > trend_score + 0.10 {
        "chop"
    } else if trend_score.is_finite() && chop_score.is_finite() {
        "transition"
    } else {
        "unclassified"
    }
}

fn regime_index(regime: &str) -> usize {
    match regime {
        "trend" => 0,
        "chop" => 1,
        "transition" => 2,
        _ => 2,
    }
}

fn validate_dimensionless_registry(config: &SupervisedConfig) -> Result<()> {
    // Older first-party artifacts predate the explicit opt-in flag, so also
    // inspect their immutable feature registry. This accepts an old artifact
    // only when its configured values/deltas are already geometry; newly
    // prepared configs carry require_dimensionless_features=true.
    for spec in &config.features {
        if matches!(
            spec.indicator,
            IndicatorKind::Sma
                | IndicatorKind::Ema
                | IndicatorKind::Hma
                | IndicatorKind::Kama
                | IndicatorKind::Alma
                | IndicatorKind::Atr
                | IndicatorKind::Close
        ) {
            if spec.include_value && !spec.normalize_value_by_atr {
                bail!(
                    "event gate rejects raw {}_{} value; reprepare with normalize_value_by_atr=true",
                    spec.indicator,
                    spec.period
                );
            }
            if spec.include_delta && !spec.normalize_by_atr {
                bail!(
                    "event gate rejects raw {}_{} delta; reprepare with normalize_by_atr=true",
                    spec.indicator,
                    spec.period
                );
            }
        }
    }
    Ok(())
}

fn reject_future_features(names: &[String]) -> Result<()> {
    for name in names {
        if name.contains("future")
            || name.contains("oracle")
            || name.contains("action_value")
            || matches!(
                name.as_str(),
                "label_action"
                    | "label_name"
                    | "decision_price"
                    | "interval_end_price"
                    | "interval_end_row_idx"
                    | "terminal_event"
            )
        {
            bail!("feature {name:?} is future/label-derived");
        }
    }
    Ok(())
}

fn split_rows(
    rows: &[Row],
    train_fraction: f64,
    validation_fraction: f64,
    purge_bars: usize,
) -> Result<Splits> {
    let mut sessions = Vec::<(String, usize)>::new();
    for (index, row) in rows.iter().enumerate() {
        if sessions
            .last()
            .is_none_or(|(session, _)| session != &row.session_id)
        {
            sessions.push((row.session_id.clone(), index));
        }
    }
    if sessions.len() < 3 {
        bail!("at least three complete sessions are required for train/validation/holdout");
    }
    let train_sessions = ((sessions.len() as f64 * train_fraction).floor() as usize)
        .max(1)
        .min(sessions.len() - 2);
    let validation_sessions = ((sessions.len() as f64 * validation_fraction).floor() as usize)
        .max(1)
        .min(sessions.len() - train_sessions - 1);
    let train_boundary = sessions[train_sessions].1;
    let validation_boundary = sessions[train_sessions + validation_sessions].1;
    let first_validation_row = rows[train_boundary].row_idx;
    let first_holdout_row = rows[validation_boundary].row_idx;
    let train_end = rows[..train_boundary]
        .iter()
        .rposition(|row| row.horizon_row_idx.saturating_add(purge_bars) < first_validation_row)
        .map(|index| index + 1)
        .unwrap_or(0);
    let validation_end = rows[train_boundary..validation_boundary]
        .iter()
        .rposition(|row| row.horizon_row_idx.saturating_add(purge_bars) < first_holdout_row)
        .map(|index| train_boundary + index + 1)
        .unwrap_or(train_boundary);
    if train_end == 0 || train_boundary >= validation_end || validation_boundary >= rows.len() {
        bail!("purge-bars leaves an empty chronological split");
    }
    Ok(Splits {
        train: 0..train_end,
        validation: train_boundary..validation_end,
        holdout: validation_boundary..rows.len(),
        purge_bars,
        session_count: sessions.len(),
    })
}

fn fit_scaler(rows: &[Row], range: &Range<usize>, feature_count: usize) -> (Vec<f64>, Vec<f64>) {
    let mut means = vec![0.0; feature_count];
    let count = range.end - range.start;
    for row in &rows[range.clone()] {
        for (mean, value) in means.iter_mut().zip(&row.raw_features) {
            *mean += *value;
        }
    }
    for mean in &mut means {
        *mean /= count as f64;
    }
    let mut scales = vec![0.0; feature_count];
    for row in &rows[range.clone()] {
        for ((scale, mean), value) in scales.iter_mut().zip(&means).zip(&row.raw_features) {
            let delta = value - mean;
            *scale += delta * delta;
        }
    }
    for scale in &mut scales {
        *scale = (*scale / count as f64).sqrt();
        if !scale.is_finite() || *scale <= 1.0e-12 {
            *scale = 1.0;
        }
    }
    (means, scales)
}

fn normalize_rows(
    rows: &[Row],
    means: &[f64],
    scales: &[f64],
    reward_scales: &BTreeMap<String, f64>,
) -> Vec<Sample> {
    rows.iter()
        .map(|row| {
            let mut features = row
                .raw_features
                .iter()
                .zip(means)
                .zip(scales)
                .map(|((value, mean), scale)| (value - mean) / scale)
                .collect::<Vec<_>>();
            features.push(1.0);
            let reward_scale = reward_scales
                .get(&row.instrument_key)
                .copied()
                .unwrap_or(1.0)
                .max(1.0);
            Sample {
                features,
                rewards: row.rewards,
                training_rewards: [row.rewards[0] / reward_scale, row.rewards[1] / reward_scale],
            }
        })
        .collect()
}

const REPLAY_STATE_FEATURES: [&str; 3] = [
    "state_position_short",
    "state_position_flat",
    "state_position_long",
];

fn replay_positions() -> [i8; 3] {
    [-1, 0, 1]
}

fn replay_position_index(position: i8) -> usize {
    match position {
        -1 => 0,
        0 => 1,
        1 => 2,
        _ => 1,
    }
}

fn replay_transition_cost(from: i8, to: i8, round_trip_cost: f64) -> f64 {
    -((from - to).unsigned_abs() as f64 * round_trip_cost / 2.0)
}

fn replay_target_position(raw_direction: i8, action: usize) -> i8 {
    if action == 0 {
        raw_direction
    } else {
        -raw_direction
    }
}

/// Compute the same position transition and session liquidation accounting
/// used by the sequential evaluator. The optimal continuation is retained as
/// an audit ceiling, while training uses only the immediate state-conditioned
/// reward so no future continuation value can be mistaken for an input.
fn build_replay_targets(rows: &[Row]) -> Result<Vec<ReplayTarget>> {
    if rows.is_empty() {
        bail!("cannot build replay targets from an empty dataset");
    }
    let mut output = vec![
        ReplayTarget {
            immediate: [[0.0; 2]; 3],
            action_values: [[0.0; 2]; 3],
            optimal_from_state: [0.0; 3],
        };
        rows.len()
    ];
    let mut session_start = 0usize;
    while session_start < rows.len() {
        let session_id = rows[session_start].session_id.clone();
        let session_end = rows[session_start..]
            .iter()
            .position(|row| row.session_id != session_id)
            .map(|offset| session_start + offset)
            .unwrap_or(rows.len());
        let terminal_cost = rows[session_end - 1].round_trip_cost;
        let mut continuation =
            replay_positions().map(|position| replay_transition_cost(position, 0, terminal_cost));
        for index in (session_start..session_end).rev() {
            let row = &rows[index];
            let delta = row.interval_end_price - row.decision_price;
            let mut immediate = [[0.0; 2]; 3];
            let mut action_values = [[0.0; 2]; 3];
            let mut best = [0.0; 3];
            for (position_index, position) in replay_positions().into_iter().enumerate() {
                for action in 0..2 {
                    let target = replay_target_position(row.raw_direction, action);
                    let target_index = replay_position_index(target);
                    immediate[position_index][action] =
                        target as f64 * delta * row.contract_multiplier
                            + replay_transition_cost(position, target, row.round_trip_cost);
                    let q = immediate[position_index][action] + continuation[target_index];
                    action_values[position_index][action] = q;
                    if action == 0 || q > best[position_index] {
                        best[position_index] = q;
                    }
                }
            }
            output[index] = ReplayTarget {
                immediate,
                action_values,
                optimal_from_state: best,
            };
            continuation = best;
        }
        session_start = session_end;
    }
    Ok(output)
}

fn replay_input_features(
    row: &Row,
    base_feature_names: &[String],
    means: &[f64],
    scales: &[f64],
    position: i8,
    regime_aware: bool,
) -> Vec<f64> {
    let base_features = row
        .raw_features
        .iter()
        .zip(means)
        .zip(scales)
        .map(|((value, mean), scale)| (value - mean) / scale)
        .collect::<Vec<_>>();
    let mut features = base_features.clone();
    for candidate in replay_positions() {
        features.push(if candidate == position { 1.0 } else { 0.0 });
    }
    if regime_aware {
        let regime = regime_bucket(base_feature_names, &row.raw_features);
        for candidate in ["trend", "chop", "transition"] {
            for value in &base_features {
                features.push(if candidate == regime { *value } else { 0.0 });
            }
        }
    }
    features.push(1.0);
    features
}

fn replay_feature_names(base: &[String], regime_aware: bool) -> Vec<String> {
    let mut names = base.to_vec();
    names.extend(REPLAY_STATE_FEATURES.into_iter().map(str::to_string));
    if regime_aware {
        for candidate in ["trend", "chop", "transition"] {
            names.extend(
                base.iter()
                    .map(|name| format!("regime_{candidate}__{name}")),
            );
        }
    }
    names
}

fn build_replay_samples(
    rows: &[Row],
    targets: &[ReplayTarget],
    base_feature_names: &[String],
    means: &[f64],
    scales: &[f64],
    reward_scales: &BTreeMap<String, f64>,
    regime_aware: bool,
) -> Vec<ReplaySample> {
    let mut samples = Vec::with_capacity(rows.len() * 3);
    for (event_index, (row, target)) in rows.iter().zip(targets).enumerate() {
        let reward_scale = reward_scales
            .get(&row.instrument_key)
            .copied()
            .unwrap_or(1.0)
            .max(1.0);
        for (position_index, position) in replay_positions().into_iter().enumerate() {
            let normal_value = target.action_values[position_index][0];
            let invert_value = target.action_values[position_index][1];
            let advantage = (normal_value - invert_value) / (2.0 * reward_scale);
            samples.push(ReplaySample {
                event_index,
                features: replay_input_features(
                    row,
                    base_feature_names,
                    means,
                    scales,
                    position,
                    regime_aware,
                ),
                // Fit the contrast, not two large action values with a
                // shared continuation component. The policy still compares
                // the two heads, so [a, -a] preserves the action ordering
                // while preventing the common future value from dominating
                // the regime signal.
                training_targets: [advantage, -advantage],
            });
        }
    }
    samples
}

fn replay_target_summary(
    rows: &[Row],
    targets: &[ReplayTarget],
    range: &Range<usize>,
    recursive: bool,
    label: &'static str,
) -> ReplayTargetSummary {
    let mut normal_sum = 0.0;
    let mut invert_sum = 0.0;
    for index in range.clone() {
        let values = if recursive {
            targets[index].action_values
        } else {
            targets[index].immediate
        };
        let normal = replay_positions()
            .into_iter()
            .map(|position| values[replay_position_index(position)][0])
            .sum::<f64>()
            / replay_positions().len() as f64;
        let invert = replay_positions()
            .into_iter()
            .map(|position| values[replay_position_index(position)][1])
            .sum::<f64>()
            / replay_positions().len() as f64;
        normal_sum += normal;
        invert_sum += invert;
    }
    let event_count = range.end.saturating_sub(range.start).min(rows.len());
    ReplayTargetSummary {
        event_count,
        label,
        equal_state_normal_mean_usd: if event_count == 0 {
            0.0
        } else {
            normal_sum / event_count as f64
        },
        equal_state_invert_mean_usd: if event_count == 0 {
            0.0
        } else {
            invert_sum / event_count as f64
        },
        equal_state_normal_sum_usd: normal_sum,
        equal_state_invert_sum_usd: invert_sum,
    }
}

fn replay_regime_target_summary(
    rows: &[Row],
    targets: &[ReplayTarget],
    range: &Range<usize>,
    base_feature_names: &[String],
    recursive: bool,
) -> BTreeMap<String, ReplayRegimeTargetSummary> {
    let mut aggregates = BTreeMap::<String, (usize, usize, usize, f64, f64)>::new();
    for index in range.clone() {
        let values = if recursive {
            targets[index].action_values
        } else {
            targets[index].immediate
        };
        let normal = replay_positions()
            .into_iter()
            .map(|position| values[replay_position_index(position)][0])
            .sum::<f64>()
            / replay_positions().len() as f64;
        let invert = replay_positions()
            .into_iter()
            .map(|position| values[replay_position_index(position)][1])
            .sum::<f64>()
            / replay_positions().len() as f64;
        let regime = regime_bucket(base_feature_names, &rows[index].raw_features).to_string();
        let entry = aggregates.entry(regime).or_default();
        entry.0 += 1;
        if normal > invert {
            entry.1 += 1;
        } else if invert > normal {
            entry.2 += 1;
        }
        entry.3 += normal;
        entry.4 += invert;
    }
    aggregates
        .into_iter()
        .map(
            |(
                regime,
                (event_count, normal_better_count, invert_better_count, normal_sum, invert_sum),
            )| {
                (
                    regime,
                    ReplayRegimeTargetSummary {
                        event_count,
                        normal_better_count,
                        invert_better_count,
                        equal_state_normal_mean_usd: normal_sum / event_count.max(1) as f64,
                        equal_state_invert_mean_usd: invert_sum / event_count.max(1) as f64,
                    },
                )
            },
        )
        .collect()
}

fn replay_sample_in_range(sample: &ReplaySample, range: &Range<usize>) -> bool {
    sample.event_index >= range.start && sample.event_index < range.end
}

fn replay_value_loss(samples: &[ReplaySample], range: &Range<usize>, policy: &Policy) -> f64 {
    let selected = samples
        .iter()
        .filter(|sample| replay_sample_in_range(sample, range))
        .collect::<Vec<_>>();
    let count = (selected.len() * 2) as f64;
    if count == 0.0 {
        return 0.0;
    }
    selected
        .into_iter()
        .flat_map(|sample| {
            let predictions = policy.value_estimates(&sample.features);
            [
                (predictions[0], sample.training_targets[0]),
                (predictions[1], sample.training_targets[1]),
            ]
        })
        .map(|(prediction, target)| {
            let error = prediction - target;
            0.5 * error * error
        })
        .sum::<f64>()
        / count
}

fn train_replay_value(
    samples: &[ReplaySample],
    rows: &[Row],
    targets: &[ReplayTarget],
    splits: &Splits,
    feature_names: &[String],
    base_feature_names: &[String],
    means: &[f64],
    scales: &[f64],
    reward_scales: &BTreeMap<String, f64>,
    epochs: usize,
    learning_rate: f64,
    l2: f64,
    checkpoint_every: usize,
    regime_aware: bool,
) -> Result<ReplayTrainResult> {
    if epochs == 0 {
        bail!("epochs must be positive");
    }
    if samples.is_empty() || rows.is_empty() {
        bail!("replay training requires non-empty samples and rows");
    }
    let mut policy = Policy::zero(feature_names.len());
    let mut best = policy.clone();
    let mut best_validation = f64::NEG_INFINITY;
    let mut selected_iteration = 0usize;
    let mut checkpoints = Vec::new();
    let train_samples = samples
        .iter()
        .filter(|sample| replay_sample_in_range(sample, &splits.train))
        .count();
    if train_samples == 0 {
        bail!("replay training split contains no state samples");
    }
    let train_count = train_samples as f64;
    for epoch in 1..=epochs {
        let mut gradients = vec![vec![0.0; feature_names.len() + 1]; 2];
        for sample in samples
            .iter()
            .filter(|sample| replay_sample_in_range(sample, &splits.train))
        {
            let predictions = policy.value_estimates(&sample.features);
            for action in 0..2 {
                let error = predictions[action] - sample.training_targets[action];
                // Targets are normalized by the training mean absolute USD
                // reward. Unit-Huber clipping would discard profitable
                // outliers and can reverse the action prior when the two
                // actions have different tails. Squared error preserves the
                // payoff ordering and matches the replay objective.
                let derivative = error;
                for (gradient, feature) in gradients[action].iter_mut().zip(&sample.features) {
                    *gradient += derivative * feature;
                }
            }
        }
        for (weights, gradient_row) in policy.weights.iter_mut().zip(gradients) {
            for (weight, gradient) in weights.iter_mut().zip(gradient_row) {
                let update = gradient / train_count + l2 * *weight;
                *weight = (*weight - learning_rate * update).clamp(-100.0, 100.0);
            }
        }
        if checkpoint_every > 0 && epoch % checkpoint_every == 0 {
            let validation = evaluate_replay(
                rows,
                targets,
                &splits.validation,
                means,
                scales,
                reward_scales,
                Some(&policy),
                None,
                None,
                base_feature_names,
                regime_aware,
            );
            if validation.sum_pnl_usd > best_validation {
                best_validation = validation.sum_pnl_usd;
                best = policy.clone();
                selected_iteration = epoch;
            }
            checkpoints.push(ReplayCheckpoint {
                iteration: epoch,
                train: evaluate_replay(
                    rows,
                    targets,
                    &splits.train,
                    means,
                    scales,
                    reward_scales,
                    Some(&policy),
                    None,
                    None,
                    base_feature_names,
                    regime_aware,
                ),
                validation,
                train_value_loss: replay_value_loss(samples, &splits.train, &policy),
                validation_value_loss: replay_value_loss(samples, &splits.validation, &policy),
            });
        }
    }
    if checkpoints.is_empty() {
        best = policy;
        selected_iteration = epochs;
    }
    Ok(ReplayTrainResult {
        policy: best,
        selected_iteration,
        checkpoints,
    })
}

fn evaluate_replay(
    rows: &[Row],
    targets: &[ReplayTarget],
    range: &Range<usize>,
    means: &[f64],
    scales: &[f64],
    _reward_scales: &BTreeMap<String, f64>,
    policy: Option<&Policy>,
    fixed_action: Option<usize>,
    regime_actions: Option<[usize; 3]>,
    base_feature_names: &[String],
    regime_aware: bool,
) -> ReplaySummary {
    let mut normal_count = 0usize;
    let mut invert_count = 0usize;
    let mut pnl = 0.0;
    let mut oracle = 0.0;
    let mut terminal_liquidation_cost = 0.0;
    let mut sessions = 0usize;
    let mut current_session: Option<&str> = None;
    let mut position = 0i8;
    let mut by_regime = BTreeMap::<String, ReplayRegimeSummary>::new();
    let mut last_regime = "unclassified";

    for index in range.clone() {
        let row = &rows[index];
        if current_session != Some(row.session_id.as_str()) {
            if current_session.is_some() {
                let cost = replay_transition_cost(position, 0, rows[index - 1].round_trip_cost);
                pnl += cost;
                terminal_liquidation_cost += -cost;
                if let Some(stats) = by_regime.get_mut(last_regime) {
                    stats.sum_pnl_usd += cost;
                }
            }
            current_session = Some(row.session_id.as_str());
            position = 0;
            sessions += 1;
            oracle += targets[index].optimal_from_state[replay_position_index(0)];
        }
        let state_index = replay_position_index(position);
        let regime = regime_bucket(base_feature_names, &row.raw_features);
        let features = replay_input_features(
            row,
            base_feature_names,
            means,
            scales,
            position,
            regime_aware,
        );
        let action = if let Some(actions) = regime_actions {
            actions[regime_index(regime)]
        } else {
            fixed_action.unwrap_or_else(|| {
                policy
                    .expect("replay policy is required when fixed_action is absent")
                    .choose_value(&features)
            })
        };
        let action = action.min(1);
        let reward = targets[index].immediate[state_index][action];
        pnl += reward;
        if action == 0 {
            normal_count += 1;
        } else {
            invert_count += 1;
        }
        last_regime = regime;
        let stats = by_regime
            .entry(regime.to_string())
            .or_insert(ReplayRegimeSummary {
                event_count: 0,
                normal_count: 0,
                invert_count: 0,
                sum_pnl_usd: 0.0,
            });
        stats.event_count += 1;
        if action == 0 {
            stats.normal_count += 1;
        } else {
            stats.invert_count += 1;
        }
        stats.sum_pnl_usd += reward;
        position = replay_target_position(row.raw_direction, action);
    }
    if current_session.is_some() && !rows[range.clone()].is_empty() {
        let cost = replay_transition_cost(position, 0, rows[range.end - 1].round_trip_cost);
        pnl += cost;
        terminal_liquidation_cost += -cost;
        if let Some(stats) = by_regime.get_mut(last_regime) {
            stats.sum_pnl_usd += cost;
        }
    }
    let count = normal_count + invert_count;
    let regret = oracle - pnl;
    ReplaySummary {
        event_count: count,
        session_count: sessions,
        normal_count,
        invert_count,
        normal_fraction: if count == 0 {
            0.0
        } else {
            normal_count as f64 / count as f64
        },
        invert_fraction: if count == 0 {
            0.0
        } else {
            invert_count as f64 / count as f64
        },
        sum_pnl_usd: pnl,
        oracle_pnl_usd: oracle,
        oracle_regret_usd: regret,
        oracle_capture: if oracle.abs() <= f64::EPSILON {
            0.0
        } else {
            pnl / oracle
        },
        terminal_liquidation_cost_usd: terminal_liquidation_cost,
        by_regime,
    }
}

fn run_replay_value(
    args: &Args,
    dataset: &Dataset,
    splits: &Splits,
    means: &[f64],
    scales: &[f64],
    reward_scales: &BTreeMap<String, f64>,
    reward_scale: f64,
) -> Result<()> {
    let targets = build_replay_targets(&dataset.rows)?;
    let base_feature_names = dataset.feature_names.clone();
    let input_feature_names = replay_feature_names(&base_feature_names, args.regime_aware);
    let samples = build_replay_samples(
        &dataset.rows,
        &targets,
        &base_feature_names,
        means,
        scales,
        reward_scales,
        args.regime_aware,
    );
    let result = train_replay_value(
        &samples,
        &dataset.rows,
        &targets,
        splits,
        &input_feature_names,
        &base_feature_names,
        means,
        scales,
        reward_scales,
        args.epochs,
        args.learning_rate,
        args.l2,
        args.checkpoint_every,
        args.regime_aware,
    )?;
    let selected_train = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.train,
        means,
        scales,
        reward_scales,
        Some(&result.policy),
        None,
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let selected_validation = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.validation,
        means,
        scales,
        reward_scales,
        Some(&result.policy),
        None,
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let fixed_normal = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.holdout,
        means,
        scales,
        reward_scales,
        None,
        Some(0),
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let fixed_invert = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.holdout,
        means,
        scales,
        reward_scales,
        None,
        Some(1),
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let learned = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.holdout,
        means,
        scales,
        reward_scales,
        Some(&result.policy),
        None,
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let fixed_normal_validation = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.validation,
        means,
        scales,
        reward_scales,
        None,
        Some(0),
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let regime_consistent = if args.regime_aware {
        fixed_normal_validation
            .by_regime
            .iter()
            .all(|(regime, baseline)| {
                selected_validation
                    .by_regime
                    .get(regime)
                    .map(|candidate| candidate.sum_pnl_usd >= baseline.sum_pnl_usd)
                    .unwrap_or(false)
            })
    } else {
        true
    };
    let use_baseline_fallback = selected_validation.sum_pnl_usd
        <= fixed_normal_validation.sum_pnl_usd
        || !regime_consistent;
    let deployment_mode = if use_baseline_fallback {
        "baseline-normal-fallback-validation".to_string()
    } else {
        "learned-replay-gate".to_string()
    };
    let deployed_policy = if use_baseline_fallback {
        Policy::zero(input_feature_names.len())
    } else {
        result.policy.clone()
    };
    let deployed_train = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.train,
        means,
        scales,
        reward_scales,
        Some(&deployed_policy),
        None,
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let deployed_validation = if use_baseline_fallback {
        fixed_normal_validation.clone()
    } else {
        selected_validation.clone()
    };
    let deployed_holdout = evaluate_replay(
        &dataset.rows,
        &targets,
        &splits.holdout,
        means,
        scales,
        reward_scales,
        Some(&deployed_policy),
        None,
        None,
        &base_feature_names,
        args.regime_aware,
    );
    let regime_policy_table = if args.regime_aware {
        let mut best_actions = [0usize; 3];
        let mut best_validation = f64::NEG_INFINITY;
        let mut best_validation_summary = None;
        for mask in 0usize..8 {
            let actions = [mask & 1, (mask >> 1) & 1, (mask >> 2) & 1];
            let validation = evaluate_replay(
                &dataset.rows,
                &targets,
                &splits.validation,
                means,
                scales,
                reward_scales,
                None,
                None,
                Some(actions),
                &base_feature_names,
                true,
            );
            if validation.sum_pnl_usd > best_validation {
                best_validation = validation.sum_pnl_usd;
                best_actions = actions;
                best_validation_summary = Some(validation);
            }
        }
        let holdout = evaluate_replay(
            &dataset.rows,
            &targets,
            &splits.holdout,
            means,
            scales,
            reward_scales,
            None,
            None,
            Some(best_actions),
            &base_feature_names,
            true,
        );
        let mut selected_actions = BTreeMap::new();
        for (regime, action) in [
            ("trend", best_actions[0]),
            ("chop", best_actions[1]),
            ("transition", best_actions[2]),
        ] {
            selected_actions.insert(
                regime.to_string(),
                if action == 0 {
                    "normal".to_string()
                } else {
                    "invert".to_string()
                },
            );
        }
        Some(ReplayRegimePolicyReport {
            selected_actions,
            validation: best_validation_summary.expect("regime policy grid has candidates"),
            holdout,
        })
    } else {
        None
    };
    let split_report = split_report(splits, dataset.rows.len());
    let train_immediate_target_summary =
        replay_target_summary(&dataset.rows, &targets, &splits.train, false, "immediate");
    let validation_immediate_target_summary = replay_target_summary(
        &dataset.rows,
        &targets,
        &splits.validation,
        false,
        "immediate",
    );
    let holdout_immediate_target_summary =
        replay_target_summary(&dataset.rows, &targets, &splits.holdout, false, "immediate");
    let train_recursive_target_summary =
        replay_target_summary(&dataset.rows, &targets, &splits.train, true, "recursive");
    let validation_recursive_target_summary = replay_target_summary(
        &dataset.rows,
        &targets,
        &splits.validation,
        true,
        "recursive",
    );
    let holdout_recursive_target_summary =
        replay_target_summary(&dataset.rows, &targets, &splits.holdout, true, "recursive");
    let train_regime_target_summary = replay_regime_target_summary(
        &dataset.rows,
        &targets,
        &splits.train,
        &base_feature_names,
        true,
    );
    let validation_regime_target_summary = replay_regime_target_summary(
        &dataset.rows,
        &targets,
        &splits.validation,
        &base_feature_names,
        true,
    );
    let holdout_regime_target_summary = replay_regime_target_summary(
        &dataset.rows,
        &targets,
        &splits.holdout,
        &base_feature_names,
        true,
    );
    let normalization = match args.reward_normalization {
        RewardNormalization::None => "none",
        RewardNormalization::TrainMeanAbs => "train-mean-abs",
    };
    let mut full_means = means.to_vec();
    full_means.extend([0.0; 3]);
    let mut full_scales = scales.to_vec();
    full_scales.extend([1.0; 3]);
    if args.regime_aware {
        full_means.extend(std::iter::repeat(0.0).take(base_feature_names.len() * 3));
        full_scales.extend(std::iter::repeat(1.0).take(base_feature_names.len() * 3));
    }
    let policy = ReplayPolicyArtifact {
        schema_version: "event-gate-replay-policy-v1",
        warning: REPLAY_MODEL_WARNING,
        input: input_display(&args.input),
        algorithm: "replay-value",
        model_semantics: REPLAY_MODEL_SEMANTICS,
        seed: args.seed,
        actions: ["normal", "invert"],
        feature_names: input_feature_names,
        base_feature_names: base_feature_names.clone(),
        config_json: dataset.config_json.clone(),
        source_hash_sha256: dataset.source_hash.clone(),
        dataset_fingerprint_sha256: dataset.dataset_fingerprint.clone(),
        reward_normalization: normalization.to_string(),
        reward_scale_usd: reward_scale,
        reward_scales_usd_by_instrument: reward_scales.clone(),
        reward_definition: REPLAY_REWARD_DEFINITION,
        label_definition: REPLAY_LABEL_DEFINITION,
        loss_definition: REPLAY_LOSS_DEFINITION,
        regime_aware: args.regime_aware,
        state_features: REPLAY_STATE_FEATURES,
        split: split_report.clone(),
        selected_iteration: result.selected_iteration,
        deployment_mode: deployment_mode.clone(),
        feature_means: full_means,
        feature_scales: full_scales,
        weights: deployed_policy.weights.clone(),
    };
    let metrics = ReplayMetricsArtifact {
        schema_version: "event-gate-replay-metrics-v1",
        warning: REPLAY_MODEL_WARNING,
        input: input_display(&args.input),
        algorithm: "replay-value",
        seed: args.seed,
        actions: ["normal", "invert"],
        feature_names: dataset.feature_names.clone(),
        model_feature_names: replay_feature_names(&base_feature_names, args.regime_aware),
        config_json: dataset.config_json.clone(),
        source_hash_sha256: dataset.source_hash.clone(),
        dataset_fingerprint_sha256: dataset.dataset_fingerprint.clone(),
        reward_normalization: normalization.to_string(),
        reward_scale_usd: reward_scale,
        reward_scales_usd_by_instrument: reward_scales.clone(),
        reward_definition: REPLAY_REWARD_DEFINITION,
        label_definition: REPLAY_LABEL_DEFINITION,
        loss_definition: REPLAY_LOSS_DEFINITION,
        regime_aware: args.regime_aware,
        state_features: REPLAY_STATE_FEATURES,
        split: split_report,
        selected_iteration: result.selected_iteration,
        deployment_mode,
        train_immediate_target_summary,
        validation_immediate_target_summary,
        holdout_immediate_target_summary,
        train_recursive_target_summary,
        validation_recursive_target_summary,
        holdout_recursive_target_summary,
        train_regime_target_summary,
        validation_regime_target_summary,
        holdout_regime_target_summary,
        regime_policy_table,
        deployed_train,
        deployed_validation,
        deployed_holdout,
        selected_train,
        selected_validation,
        fixed_normal_validation,
        fixed_normal,
        fixed_invert,
        learned,
        checkpoints: result.checkpoints,
        leakage_check: "passed",
    };
    write_json(&args.outdir, "policy.json", &policy)?;
    write_json(&args.outdir, "metrics.json", &metrics)?;
    println!("{}", serde_json::to_string_pretty(&metrics)?);
    Ok(())
}

fn fit_reward_scales(
    rows: &[Row],
    range: &Range<usize>,
    mode: RewardNormalization,
) -> BTreeMap<String, f64> {
    let mut sums = BTreeMap::<String, (f64, usize)>::new();
    for row in &rows[range.clone()] {
        let entry = sums.entry(row.instrument_key.clone()).or_default();
        entry.0 += row.rewards[0].abs() + row.rewards[1].abs();
        entry.1 += 2;
    }
    sums.into_iter()
        .map(|(instrument, (sum, count))| {
            let scale = if matches!(mode, RewardNormalization::None) {
                1.0
            } else {
                (sum / count.max(1) as f64).max(1.0)
            };
            (instrument, scale)
        })
        .collect()
}

fn reported_reward_scale(scales: &BTreeMap<String, f64>, mixed: bool) -> f64 {
    if mixed {
        1.0
    } else {
        scales.values().next().copied().unwrap_or(1.0)
    }
}

fn train_ga(
    samples: &[Sample],
    splits: &Splits,
    generations: usize,
    population_size: usize,
    seed: u64,
    reward_scale: f64,
    checkpoint_every: usize,
    mutation_rate: f64,
    mutation_step: f64,
) -> Result<TrainResult> {
    if generations == 0 {
        bail!("generations must be positive");
    }
    let feature_count = samples[0].features.len() - 1;
    let mut rng = StdRng::seed_from_u64(seed);
    let mut population = Vec::with_capacity(population_size);
    population.push(Policy::zero(feature_count));
    for _ in 1..population_size {
        population.push(Policy::random(feature_count, &mut rng, 0.05));
    }
    let mut best_validation = f64::NEG_INFINITY;
    let mut selected = population[0].clone();
    let mut selected_iteration = 0;
    let mut checkpoints = Vec::new();
    for generation in 1..=generations {
        let mut scored = population
            .into_iter()
            .map(|policy| (score(&policy, samples, &splits.train, reward_scale), policy))
            .collect::<Vec<_>>();
        scored.sort_by(|left, right| right.0.total_cmp(&left.0));
        let candidate = &scored[0].1;
        let validation = evaluate(samples, &splits.validation, candidate);
        if validation.sum_pnl_usd > best_validation {
            best_validation = validation.sum_pnl_usd;
            selected = candidate.clone();
            selected_iteration = generation;
        }
        if checkpoint_every > 0 && generation % checkpoint_every == 0 {
            checkpoints.push(Checkpoint {
                iteration: generation,
                train: evaluate(samples, &splits.train, candidate),
                validation,
                train_value_loss: None,
                validation_value_loss: None,
            });
        }
        let elite_count = (population_size / 5).max(1).min(population_size);
        let mut next = scored
            .iter()
            .take(elite_count)
            .map(|(_, policy)| policy.clone())
            .collect::<Vec<_>>();
        while next.len() < population_size {
            let parent = rng.gen_range(0..elite_count);
            let mut child = scored[parent].1.clone();
            child.mutate(&mut rng, mutation_rate, mutation_step);
            next.push(child);
        }
        population = next;
    }
    Ok(TrainResult {
        policy: selected,
        selected_iteration,
        checkpoints,
    })
}

fn train_rl(
    samples: &[Sample],
    splits: &Splits,
    epochs: usize,
    seed: u64,
    _reward_scale: f64,
    checkpoint_every: usize,
    learning_rate: f64,
    l2: f64,
) -> Result<TrainResult> {
    if epochs == 0 {
        bail!("epochs must be positive");
    }
    let feature_count = samples[0].features.len() - 1;
    let mut rng = StdRng::seed_from_u64(seed);
    let mut policy = Policy::random(feature_count, &mut rng, 0.01);
    let mut best = policy.clone();
    let mut best_validation = f64::NEG_INFINITY;
    let mut selected_iteration = 0;
    let mut checkpoints = Vec::new();
    let train_count = (splits.train.end - splits.train.start) as f64;
    for epoch in 1..=epochs {
        let mut gradients = vec![vec![0.0; feature_count + 1]; 2];
        for sample in &samples[splits.train.clone()] {
            let probabilities = policy.probabilities(&sample.features);
            let rewards = sample.training_rewards;
            let expected = probabilities[0] * rewards[0] + probabilities[1] * rewards[1];
            for action in 0..2 {
                let logit_gradient = probabilities[action] * (rewards[action] - expected);
                for (gradient, feature) in gradients[action].iter_mut().zip(&sample.features) {
                    *gradient += logit_gradient * feature;
                }
            }
        }
        for (weights, gradient_row) in policy.weights.iter_mut().zip(gradients) {
            for (weight, gradient) in weights.iter_mut().zip(gradient_row) {
                let update = (gradient / train_count - l2 * *weight).clamp(-1.0, 1.0);
                *weight = (*weight + learning_rate * update).clamp(-20.0, 20.0);
            }
        }
        if checkpoint_every > 0 && epoch % checkpoint_every == 0 {
            let validation = evaluate(samples, &splits.validation, &policy);
            if validation.sum_pnl_usd > best_validation {
                best_validation = validation.sum_pnl_usd;
                best = policy.clone();
                selected_iteration = epoch;
            }
            checkpoints.push(Checkpoint {
                iteration: epoch,
                train: evaluate(samples, &splits.train, &policy),
                validation,
                train_value_loss: None,
                validation_value_loss: None,
            });
        }
    }
    if checkpoints.is_empty() {
        best = policy;
        selected_iteration = epochs;
    }
    Ok(TrainResult {
        policy: best,
        selected_iteration,
        checkpoints,
    })
}

fn train_value(
    samples: &[Sample],
    splits: &Splits,
    epochs: usize,
    reward_scale: f64,
    checkpoint_every: usize,
    learning_rate: f64,
    l2: f64,
) -> Result<TrainResult> {
    if epochs == 0 {
        bail!("epochs must be positive");
    }
    let feature_count = samples[0].features.len() - 1;
    let mut policy = Policy::zero(feature_count);
    let mut best = policy.clone();
    let mut best_validation = f64::NEG_INFINITY;
    let mut selected_iteration = 0;
    let mut checkpoints = Vec::new();
    let train_count = (splits.train.end - splits.train.start) as f64;
    // A robust loss keeps a few unusually large GC moves from dominating the
    // linear action-value fit while preserving the USD reward for evaluation.
    const HUBER_DELTA: f64 = 1.0;

    for epoch in 1..=epochs {
        let mut gradients = vec![vec![0.0; feature_count + 1]; 2];
        let mut train_loss = 0.0;
        for sample in &samples[splits.train.clone()] {
            let targets = sample.training_rewards;
            let predictions = policy.value_estimates(&sample.features);
            for action in 0..2 {
                let error = predictions[action] - targets[action];
                let absolute_error = error.abs();
                let (loss, derivative) = if absolute_error <= HUBER_DELTA {
                    (0.5 * error * error, error)
                } else {
                    (
                        HUBER_DELTA * (absolute_error - 0.5 * HUBER_DELTA),
                        HUBER_DELTA * error.signum(),
                    )
                };
                train_loss += loss;
                for (gradient, feature) in gradients[action].iter_mut().zip(&sample.features) {
                    *gradient += derivative * feature;
                }
            }
        }
        for (weights, gradient_row) in policy.weights.iter_mut().zip(gradients) {
            for (weight, gradient) in weights.iter_mut().zip(gradient_row) {
                let update = gradient / train_count + l2 * *weight;
                *weight = (*weight - learning_rate * update).clamp(-100.0, 100.0);
            }
        }

        if checkpoint_every > 0 && epoch % checkpoint_every == 0 {
            let validation = evaluate_value(samples, &splits.validation, &policy);
            if validation.sum_pnl_usd > best_validation {
                best_validation = validation.sum_pnl_usd;
                best = policy.clone();
                selected_iteration = epoch;
            }
            let validation_loss = value_loss(samples, &splits.validation, &policy, reward_scale);
            checkpoints.push(Checkpoint {
                iteration: epoch,
                train: evaluate_value(samples, &splits.train, &policy),
                validation,
                train_value_loss: Some(train_loss / (train_count * 2.0)),
                validation_value_loss: Some(validation_loss),
            });
        }
    }
    if checkpoints.is_empty() {
        best = policy;
        selected_iteration = epochs;
    }
    Ok(TrainResult {
        policy: best,
        selected_iteration,
        checkpoints,
    })
}

const ADVANTAGE_TARGET_DEFINITION: &str = "normalized direct advantage: (normal_reward - invert_reward) / (2 * train_reward_scale); fees cancel and the sign selects the action";

fn normalized_advantage(sample: &Sample, reward_scale: f64) -> f64 {
    let _ = reward_scale;
    (sample.training_rewards[0] - sample.training_rewards[1]) / 2.0
}

fn huber_loss_derivative(error: f64) -> (f64, f64) {
    const HUBER_DELTA: f64 = 1.0;
    let absolute_error = error.abs();
    if absolute_error <= HUBER_DELTA {
        (0.5 * error * error, error)
    } else {
        (
            HUBER_DELTA * (absolute_error - 0.5 * HUBER_DELTA),
            HUBER_DELTA * error.signum(),
        )
    }
}

fn evaluate_advantage(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &AdvantagePolicy,
) -> Summary {
    evaluate_with(samples, range, |sample| {
        if policy.predict(&sample.features) >= 0.0 {
            0
        } else {
            1
        }
    })
}

impl AdvantagePolicy {
    fn zero(feature_count_with_bias: usize) -> Self {
        Self {
            weights: vec![0.0; feature_count_with_bias],
        }
    }

    fn predict(&self, features: &[f64]) -> f64 {
        self.weights
            .iter()
            .zip(features)
            .map(|(weight, feature)| weight * feature)
            .sum()
    }
}

fn advantage_loss(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &AdvantagePolicy,
    reward_scale: f64,
) -> f64 {
    let count = (range.end - range.start) as f64;
    if count <= 0.0 {
        return 0.0;
    }
    samples[range.clone()]
        .iter()
        .map(|sample| {
            let error =
                policy.predict(&sample.features) - normalized_advantage(sample, reward_scale);
            huber_loss_derivative(error).0
        })
        .sum::<f64>()
        / count
}

fn train_advantage(
    samples: &[Sample],
    splits: &Splits,
    epochs: usize,
    checkpoint_every: usize,
    learning_rate: f64,
    l2: f64,
    reward_scale: f64,
) -> Result<AdvantageTrainResult> {
    if epochs == 0 {
        bail!("epochs must be positive");
    }
    let feature_count = samples[0].features.len();
    let mut policy = AdvantagePolicy::zero(feature_count);
    let mut best = policy.clone();
    let mut best_validation = f64::NEG_INFINITY;
    let mut selected_iteration = 0;
    let mut checkpoints = Vec::new();
    let train_count = (splits.train.end - splits.train.start) as f64;

    for epoch in 1..=epochs {
        let mut gradients = vec![0.0; feature_count];
        let mut train_loss = 0.0;
        for sample in &samples[splits.train.clone()] {
            let error =
                policy.predict(&sample.features) - normalized_advantage(sample, reward_scale);
            let (loss, derivative) = huber_loss_derivative(error);
            train_loss += loss;
            for (gradient, feature) in gradients.iter_mut().zip(&sample.features) {
                *gradient += derivative * feature;
            }
        }
        for (weight, gradient) in policy.weights.iter_mut().zip(gradients) {
            let update = gradient / train_count + l2 * *weight;
            *weight = (*weight - learning_rate * update).clamp(-100.0, 100.0);
        }

        if checkpoint_every > 0 && epoch % checkpoint_every == 0 {
            let validation = evaluate_advantage(samples, &splits.validation, &policy);
            if validation.sum_pnl_usd > best_validation {
                best_validation = validation.sum_pnl_usd;
                best = policy.clone();
                selected_iteration = epoch;
            }
            checkpoints.push(Checkpoint {
                iteration: epoch,
                train: evaluate_advantage(samples, &splits.train, &policy),
                validation,
                train_value_loss: Some(train_loss / train_count),
                validation_value_loss: Some(advantage_loss(
                    samples,
                    &splits.validation,
                    &policy,
                    reward_scale,
                )),
            });
        }
    }
    if checkpoints.is_empty() {
        best = policy;
        selected_iteration = epochs;
    }
    Ok(AdvantageTrainResult {
        policy: best,
        selected_iteration,
        checkpoints,
    })
}

impl MlpPolicy {
    fn random(feature_count: usize, hidden_size: usize, seed: u64) -> Self {
        let mut rng = StdRng::seed_from_u64(seed);
        let hidden_weights = (0..hidden_size)
            .map(|_| {
                (0..feature_count)
                    .map(|_| rng.gen_range(-0.02..0.02))
                    .collect::<Vec<_>>()
            })
            .collect::<Vec<_>>();
        Self {
            hidden_weights,
            hidden_bias: vec![0.0; hidden_size],
            output_weights: (0..hidden_size)
                .map(|_| rng.gen_range(-0.02..0.02))
                .collect(),
            output_bias: 0.0,
        }
    }

    fn predict_with_hidden(&self, features: &[f64]) -> (Vec<f64>, f64) {
        let input = &features[..self.hidden_weights[0].len()];
        let hidden = self
            .hidden_weights
            .iter()
            .zip(&self.hidden_bias)
            .map(|(weights, bias)| {
                let activation = weights
                    .iter()
                    .zip(input)
                    .map(|(weight, feature)| weight * feature)
                    .sum::<f64>()
                    + bias;
                activation.tanh()
            })
            .collect::<Vec<_>>();
        let output = self
            .output_weights
            .iter()
            .zip(&hidden)
            .map(|(weight, activation)| weight * activation)
            .sum::<f64>()
            + self.output_bias;
        (hidden, output)
    }

    fn predict(&self, features: &[f64]) -> f64 {
        self.predict_with_hidden(features).1
    }
}

fn evaluate_mlp(samples: &[Sample], range: &Range<usize>, policy: &MlpPolicy) -> Summary {
    evaluate_with(samples, range, |sample| {
        if policy.predict(&sample.features) >= 0.0 {
            0
        } else {
            1
        }
    })
}

fn mlp_loss(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &MlpPolicy,
    reward_scale: f64,
) -> f64 {
    let count = (range.end - range.start) as f64;
    if count <= 0.0 {
        return 0.0;
    }
    samples[range.clone()]
        .iter()
        .map(|sample| {
            let error =
                policy.predict(&sample.features) - normalized_advantage(sample, reward_scale);
            huber_loss_derivative(error).0
        })
        .sum::<f64>()
        / count
}

fn train_mlp(
    samples: &[Sample],
    splits: &Splits,
    hidden_size: usize,
    epochs: usize,
    seed: u64,
    checkpoint_every: usize,
    learning_rate: f64,
    l2: f64,
    reward_scale: f64,
) -> Result<MlpTrainResult> {
    if epochs == 0 {
        bail!("epochs must be positive");
    }
    if hidden_size == 0 {
        bail!("hidden size must be positive");
    }
    let feature_count = samples[0].features.len() - 1;
    let mut policy = MlpPolicy::random(feature_count, hidden_size, seed);
    let mut best = policy.clone();
    let mut best_validation = f64::NEG_INFINITY;
    let mut selected_iteration = 0;
    let mut checkpoints = Vec::new();
    let train_count = (splits.train.end - splits.train.start) as f64;

    for epoch in 1..=epochs {
        let mut hidden_gradients = vec![vec![0.0; feature_count]; hidden_size];
        let mut hidden_bias_gradients = vec![0.0; hidden_size];
        let mut output_gradients = vec![0.0; hidden_size];
        let mut output_bias_gradient = 0.0;
        let mut train_loss = 0.0;
        for sample in &samples[splits.train.clone()] {
            let (hidden, prediction) = policy.predict_with_hidden(&sample.features);
            let error = prediction - normalized_advantage(sample, reward_scale);
            let (loss, derivative) = huber_loss_derivative(error);
            train_loss += loss;
            output_bias_gradient += derivative;
            for (gradient, activation) in output_gradients.iter_mut().zip(&hidden) {
                *gradient += derivative * activation;
            }
            for hidden_index in 0..hidden_size {
                let backprop = derivative
                    * policy.output_weights[hidden_index]
                    * (1.0 - hidden[hidden_index] * hidden[hidden_index]);
                hidden_bias_gradients[hidden_index] += backprop;
                for (gradient, feature) in hidden_gradients[hidden_index]
                    .iter_mut()
                    .zip(&sample.features[..feature_count])
                {
                    *gradient += backprop * feature;
                }
            }
        }
        for hidden_index in 0..hidden_size {
            for feature_index in 0..feature_count {
                let weight = &mut policy.hidden_weights[hidden_index][feature_index];
                let update =
                    hidden_gradients[hidden_index][feature_index] / train_count + l2 * *weight;
                *weight = (*weight - learning_rate * update).clamp(-10.0, 10.0);
            }
            let bias_update = hidden_bias_gradients[hidden_index] / train_count;
            policy.hidden_bias[hidden_index] =
                (policy.hidden_bias[hidden_index] - learning_rate * bias_update).clamp(-10.0, 10.0);
            let output_weight = &mut policy.output_weights[hidden_index];
            let output_update = output_gradients[hidden_index] / train_count + l2 * *output_weight;
            *output_weight = (*output_weight - learning_rate * output_update).clamp(-10.0, 10.0);
        }
        policy.output_bias -= learning_rate * output_bias_gradient / train_count;

        if checkpoint_every > 0 && epoch % checkpoint_every == 0 {
            let validation = evaluate_mlp(samples, &splits.validation, &policy);
            if validation.sum_pnl_usd > best_validation {
                best_validation = validation.sum_pnl_usd;
                best = policy.clone();
                selected_iteration = epoch;
            }
            checkpoints.push(Checkpoint {
                iteration: epoch,
                train: evaluate_mlp(samples, &splits.train, &policy),
                validation,
                train_value_loss: Some(train_loss / train_count),
                validation_value_loss: Some(mlp_loss(
                    samples,
                    &splits.validation,
                    &policy,
                    reward_scale,
                )),
            });
        }
    }
    if checkpoints.is_empty() {
        best = policy;
        selected_iteration = epochs;
    }
    Ok(MlpTrainResult {
        policy: best,
        selected_iteration,
        checkpoints,
    })
}

