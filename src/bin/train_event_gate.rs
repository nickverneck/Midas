fn orientation_prior_scope_name(scope: OrientationPriorScope) -> &'static str {
    match scope {
        OrientationPriorScope::Global => "global",
        OrientationPriorScope::Session => "session",
        OrientationPriorScope::Contract => "contract",
    }
}

fn orientation_scope_key(row: &Row, scope: OrientationPriorScope) -> Option<&str> {
    match scope {
        OrientationPriorScope::Global => None,
        OrientationPriorScope::Session => Some(row.session_id.as_str()),
        OrientationPriorScope::Contract => Some(
            row.session_id
                .split_once("::")
                .map(|(contract, _)| contract)
                .unwrap_or(row.session_id.as_str()),
        ),
    }
}

/// Build an online orientation prior for every event. At row index, only
/// earlier events whose fixed horizon has already ended by the current
/// crossover row can contribute. The prior is positive when recent settled
/// events favored normal and negative when they favored invert. Session and
/// contract scopes reset the history at their respective causal boundaries.
fn settled_orientation_prior(
    rows: &[Row],
    window_events: usize,
    reward_scale: f64,
    scope: OrientationPriorScope,
) -> Vec<f64> {
    let mut output = vec![0.0; rows.len()];
    for index in 0..rows.len() {
        let current_row_idx = rows[index].row_idx;
        let current_scope = orientation_scope_key(&rows[index], scope);
        let mut count = 0usize;
        let mut total = 0.0;
        for previous in (0..index).rev() {
            if orientation_scope_key(&rows[previous], scope) != current_scope {
                continue;
            }
            if rows[previous].horizon_row_idx > current_row_idx {
                continue;
            }
            total += (rows[previous].rewards[0] - rows[previous].rewards[1]) / (2.0 * reward_scale);
            count += 1;
            if count == window_events {
                break;
            }
        }
        output[index] = if count == 0 {
            0.0
        } else {
            total / count as f64
        };
    }
    output
}

fn evaluate_with_orientation_prior(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &Policy,
    prior: &[f64],
    strength: f64,
) -> Summary {
    let mut normal_count = 0;
    let mut invert_count = 0;
    let mut pnl = 0.0;
    let mut oracle = 0.0;
    let mut positive = 0;
    for index in range.clone() {
        let values = policy.value_estimates(&samples[index].features);
        // prior is normal-minus-invert. The model margin is
        // invert-minus-normal, so a positive normal prior is subtracted.
        let margin = values[1] - values[0] - strength * prior[index];
        let action = if margin > 0.0 { 1 } else { 0 };
        if action == 0 {
            normal_count += 1;
        } else {
            invert_count += 1;
        }
        pnl += samples[index].rewards[action];
        oracle += samples[index].rewards[0].max(samples[index].rewards[1]);
        if samples[index].rewards[action] > 0.0 {
            positive += 1;
        }
    }
    let count = normal_count + invert_count;
    let regret = oracle - pnl;
    Summary {
        event_count: count,
        normal_count,
        invert_count,
        normal_fraction: if count == 0 {
            0.0
        } else {
            normal_count as f64 / count as f64
        },
        invert_fraction: if count == 0 {
            0.0
        } else {
            invert_count as f64 / count as f64
        },
        sum_pnl_usd: pnl,
        mean_pnl_usd: if count == 0 { 0.0 } else { pnl / count as f64 },
        oracle_pnl_usd: oracle,
        oracle_regret_usd: regret,
        oracle_capture: if oracle.abs() <= f64::EPSILON {
            0.0
        } else {
            pnl / oracle
        },
        positive_event_fraction: if count == 0 {
            0.0
        } else {
            positive as f64 / count as f64
        },
    }
}

fn orientation_prior_report(
    rows: &[Row],
    samples: &[Sample],
    splits: &Splits,
    policy: &Policy,
    reward_scale: f64,
    windows: &[usize],
    strengths: &[f64],
    scope: OrientationPriorScope,
) -> Result<OrientationPriorReport> {
    if rows.len() != samples.len() {
        bail!("orientation prior rows and samples have different lengths");
    }
    if !reward_scale.is_finite() || reward_scale <= 0.0 {
        bail!("orientation prior requires a positive reward scale");
    }
    if windows.is_empty()
        || windows.iter().any(|window| *window == 0)
        || strengths.is_empty()
        || strengths
            .iter()
            .any(|strength| !strength.is_finite() || *strength < 0.0)
    {
        bail!("orientation prior grid contains invalid windows or strengths");
    }
    let mut candidates = Vec::with_capacity(windows.len() * strengths.len());
    for window in windows {
        let prior = settled_orientation_prior(rows, *window, reward_scale, scope);
        for strength in strengths {
            candidates.push(OrientationPriorCandidate {
                window_events: *window,
                strength: *strength,
                validation: evaluate_with_orientation_prior(
                    samples,
                    &splits.validation,
                    policy,
                    &prior,
                    *strength,
                ),
                holdout: evaluate_with_orientation_prior(
                    samples,
                    &splits.holdout,
                    policy,
                    &prior,
                    *strength,
                ),
            });
        }
    }
    let selected = candidates
        .iter()
        .max_by(|left, right| {
            left.validation
                .sum_pnl_usd
                .total_cmp(&right.validation.sum_pnl_usd)
        })
        .ok_or_else(|| anyhow::anyhow!("orientation prior grid produced no candidates"))?;
    Ok(OrientationPriorReport {
        scope: orientation_prior_scope_name(scope).to_string(),
        selected_window_events: selected.window_events,
        selected_strength: selected.strength,
        selected_validation: selected.validation.clone(),
        selected_holdout: selected.holdout.clone(),
        candidates,
    })
}

fn evaluate_policy(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &Policy,
    value_model: bool,
) -> Summary {
    if value_model {
        evaluate_value(samples, range, policy)
    } else {
        evaluate(samples, range, policy)
    }
}

fn value_loss(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &Policy,
    _reward_scale: f64,
) -> f64 {
    const HUBER_DELTA: f64 = 1.0;
    let count = ((range.end - range.start) * 2) as f64;
    if count <= 0.0 {
        return 0.0;
    }
    samples[range.clone()]
        .iter()
        .flat_map(|sample| {
            let predictions = policy.value_estimates(&sample.features);
            [
                (predictions[0], sample.training_rewards[0]),
                (predictions[1], sample.training_rewards[1]),
            ]
        })
        .map(|(prediction, target)| {
            let absolute_error = (prediction - target).abs();
            if absolute_error <= HUBER_DELTA {
                0.5 * absolute_error * absolute_error
            } else {
                HUBER_DELTA * (absolute_error - 0.5 * HUBER_DELTA)
            }
        })
        .sum::<f64>()
        / count
}

fn explain_events(
    rows: &[Row],
    feature_names: &[String],
    means: &[f64],
    scales: &[f64],
    reward_scale: f64,
    policy: &Policy,
    requested_ids: &[usize],
    top_n: usize,
) -> Result<Vec<EventExplanation>> {
    if feature_names.len() != means.len() || means.len() != scales.len() {
        bail!("feature scaler dimensions do not match the feature registry");
    }
    let mut explanations = Vec::with_capacity(requested_ids.len());
    for event_id in requested_ids {
        let row = rows
            .iter()
            .find(|row| row.event_id == *event_id)
            .ok_or_else(|| {
                let first = rows.first().map(|row| row.event_id);
                let last = rows.last().map(|row| row.event_id);
                anyhow::anyhow!(
                    "event_id {event_id} was not found (available event-id range: {first:?}..={last:?})"
                )
            })?;
        let mut standardized = row
            .raw_features
            .iter()
            .zip(means)
            .zip(scales)
            .map(|((value, mean), scale)| (value - mean) / scale)
            .collect::<Vec<_>>();
        standardized.push(1.0);
        let estimates = policy.value_estimates(&standardized);
        let chosen_action = if estimates[1] > estimates[0] {
            "invert"
        } else {
            "normal"
        };
        let normal_contributions =
            top_contributions(feature_names, &standardized, &policy.weights[0], top_n);
        let invert_contributions =
            top_contributions(feature_names, &standardized, &policy.weights[1], top_n);
        explanations.push(EventExplanation {
            event_id: row.event_id,
            session_id: row.session_id.clone(),
            row_idx: row.row_idx,
            horizon_row_idx: row.horizon_row_idx,
            timestamp_ns: row.timestamp_ns,
            raw_direction: row.raw_direction,
            decision_price: row.decision_price,
            interval_end_price: row.interval_end_price,
            actual_normal_usd: row.rewards[0],
            actual_invert_usd: row.rewards[1],
            predicted_normal_normalized: estimates[0],
            predicted_invert_normalized: estimates[1],
            predicted_normal_usd: estimates[0] * reward_scale,
            predicted_invert_usd: estimates[1] * reward_scale,
            chosen_action: chosen_action.to_string(),
            margin_normalized_invert_minus_normal: estimates[1] - estimates[0],
            margin_usd_invert_minus_normal: (estimates[1] - estimates[0]) * reward_scale,
            normal_bias_contribution: *policy.weights[0]
                .last()
                .ok_or_else(|| anyhow::anyhow!("normal value head has no bias"))?,
            invert_bias_contribution: *policy.weights[1]
                .last()
                .ok_or_else(|| anyhow::anyhow!("invert value head has no bias"))?,
            normal_contributions,
            invert_contributions,
        });
    }
    Ok(explanations)
}

fn top_contributions(
    feature_names: &[String],
    standardized: &[f64],
    weights: &[f64],
    top_n: usize,
) -> Vec<Contribution> {
    let mut contributions = feature_names
        .iter()
        .enumerate()
        .map(|(index, feature)| Contribution {
            feature: feature.clone(),
            standardized_value: standardized[index],
            weight: weights[index],
            contribution: standardized[index] * weights[index],
        })
        .collect::<Vec<_>>();
    contributions
        .sort_by(|left, right| right.contribution.abs().total_cmp(&left.contribution.abs()));
    contributions.truncate(top_n);
    contributions
}

fn calibration_report(
    samples: &[Sample],
    splits: &Splits,
    policy: &Policy,
    margin_thresholds: &[f64],
    prior_offsets: &[f64],
    fallback: FallbackAction,
) -> Result<CalibrationReport> {
    if margin_thresholds.is_empty() || prior_offsets.is_empty() {
        bail!("calibration threshold and prior grids must not be empty");
    }
    if margin_thresholds
        .iter()
        .any(|value| !value.is_finite() || *value < 0.0)
        || prior_offsets.iter().any(|value| !value.is_finite())
    {
        bail!("calibration threshold/prior values must be finite; thresholds must be non-negative");
    }
    let mut candidates = Vec::with_capacity(margin_thresholds.len() * prior_offsets.len());
    for threshold in margin_thresholds {
        for offset in prior_offsets {
            candidates.push(CalibrationCandidate {
                margin_threshold_normalized: *threshold,
                prior_offset_normalized: *offset,
                validation: evaluate_calibrated(
                    samples,
                    &splits.validation,
                    policy,
                    *threshold,
                    *offset,
                    fallback,
                ),
                holdout: evaluate_calibrated(
                    samples,
                    &splits.holdout,
                    policy,
                    *threshold,
                    *offset,
                    fallback,
                ),
            });
        }
    }
    let selected = candidates
        .iter()
        .max_by(|left, right| {
            left.validation
                .sum_pnl_usd
                .total_cmp(&right.validation.sum_pnl_usd)
        })
        .ok_or_else(|| anyhow::anyhow!("calibration grid produced no candidates"))?;
    Ok(CalibrationReport {
        fallback_action: fallback_name(fallback).to_string(),
        selected_margin_threshold_normalized: selected.margin_threshold_normalized,
        selected_prior_offset_normalized: selected.prior_offset_normalized,
        selected_validation: selected.validation.clone(),
        selected_holdout: selected.holdout.clone(),
        candidates,
    })
}

fn evaluate_calibrated(
    samples: &[Sample],
    range: &Range<usize>,
    policy: &Policy,
    margin_threshold: f64,
    prior_offset: f64,
    fallback: FallbackAction,
) -> Summary {
    evaluate_with(samples, range, |sample| {
        let values = policy.value_estimates(&sample.features);
        let margin = values[1] - values[0] + prior_offset;
        if margin.abs() < margin_threshold {
            fallback_action_index(fallback)
        } else if margin > 0.0 {
            1
        } else {
            0
        }
    })
}

fn fallback_action_index(action: FallbackAction) -> usize {
    match action {
        FallbackAction::Normal => 0,
        FallbackAction::Invert => 1,
    }
}

fn fallback_name(action: FallbackAction) -> &'static str {
    match action {
        FallbackAction::Normal => "normal",
        FallbackAction::Invert => "invert",
    }
}

fn evaluate_saved_policy(args: &Args, policy_path: &Path) -> Result<()> {
    let policy_file = File::open(policy_path)
        .with_context(|| format!("open saved policy {}", policy_path.display()))?;
    let saved: LoadedPolicy = serde_json::from_reader(policy_file)
        .with_context(|| format!("decode saved policy {}", policy_path.display()))?;
    if saved.schema_version != "event-gate-policy-v1" {
        bail!("unsupported saved policy schema {}", saved.schema_version);
    }
    if saved.algorithm != "value" || saved.model_semantics != "normalized_action_value_regression" {
        bail!("saved policy is not an explainable normalized action-value model");
    }
    if !saved.reward_scale_usd.is_finite() || saved.reward_scale_usd <= 0.0 {
        bail!("saved policy reward_scale_usd must be positive");
    }
    if saved.feature_names.len() != saved.feature_means.len()
        || saved.feature_names.len() != saved.feature_scales.len()
        || saved.weights.len() != 2
        || saved
            .weights
            .iter()
            .any(|weights| weights.len() != saved.feature_names.len() + 1)
    {
        bail!("saved policy feature/scaler/weight dimensions are inconsistent");
    }
    let mut dataset = load_datasets(
        &args.input,
        args.feature_filter.as_deref(),
        args.allow_mixed_instruments,
    )?;
    let saved_uses_history = saved
        .feature_names
        .iter()
        .any(|name| name == "settled_history_count");
    if args.causal_history || saved_uses_history {
        append_causal_history_features(&mut dataset)?;
    }
    if dataset.feature_names != saved.feature_names {
        bail!("saved policy feature registry does not match the input parquet");
    }
    let splits = split_rows(
        &dataset.rows,
        args.train_fraction,
        args.validation_fraction,
        args.purge_bars,
    )?;
    let saved_scales = dataset
        .rows
        .iter()
        .map(|row| (row.instrument_key.clone(), saved.reward_scale_usd))
        .collect::<BTreeMap<_, _>>();
    let samples = normalize_rows(
        &dataset.rows,
        &saved.feature_means,
        &saved.feature_scales,
        &saved_scales,
    );
    let policy = Policy {
        weights: saved.weights,
    };
    let calibration = calibration_report(
        &samples,
        &splits,
        &policy,
        &args.margin_thresholds,
        &args.prior_offsets,
        args.confidence_fallback,
    )?;
    let walk_forward_prior = if args.walk_forward_prior {
        Some(orientation_prior_report(
            &dataset.rows,
            &samples,
            &splits,
            &policy,
            saved.reward_scale_usd,
            &args.orientation_prior_windows,
            &args.orientation_prior_strengths,
            args.orientation_prior_scope,
        )?)
    } else {
        None
    };
    let artifact = EvaluationArtifact {
        schema_version: "event-gate-evaluation-v1",
        policy_path: policy_path.display().to_string(),
        input: input_display(&args.input),
        selected_train: evaluate_value(&samples, &splits.train, &policy),
        selected_validation: evaluate_value(&samples, &splits.validation, &policy),
        fixed_normal: evaluate_fixed(&samples, &splits.holdout, 0),
        fixed_invert: evaluate_fixed(&samples, &splits.holdout, 1),
        learned: evaluate_value(&samples, &splits.holdout, &policy),
        calibration,
        walk_forward_prior,
        leakage_check: "passed",
    };
    write_json(&args.outdir, "evaluation.json", &artifact)?;
    if !args.explain_event.is_empty() {
        let explanations = explain_events(
            &dataset.rows,
            &dataset.feature_names,
            &saved.feature_means,
            &saved.feature_scales,
            saved.reward_scale_usd,
            &policy,
            &args.explain_event,
            args.explain_top,
        )?;
        write_json(&args.outdir, "explanations.json", &explanations)?;
    }
    println!("{}", serde_json::to_string_pretty(&artifact)?);
    Ok(())
}

fn evaluate_with<F>(samples: &[Sample], range: &Range<usize>, mut choose: F) -> Summary
where
    F: FnMut(&Sample) -> usize,
{
    let mut normal_count = 0;
    let mut invert_count = 0;
    let mut pnl = 0.0;
    let mut oracle = 0.0;
    let mut positive = 0;
    for sample in &samples[range.clone()] {
        let action = choose(sample);
        if action == 0 {
            normal_count += 1;
        } else {
            invert_count += 1;
        }
        pnl += sample.rewards[action];
        oracle += sample.rewards[0].max(sample.rewards[1]);
        if sample.rewards[action] > 0.0 {
            positive += 1;
        }
    }
    let count = normal_count + invert_count;
    let regret = oracle - pnl;
    Summary {
        event_count: count,
        normal_count,
        invert_count,
        normal_fraction: if count == 0 {
            0.0
        } else {
            normal_count as f64 / count as f64
        },
        invert_fraction: if count == 0 {
            0.0
        } else {
            invert_count as f64 / count as f64
        },
        sum_pnl_usd: pnl,
        mean_pnl_usd: if count == 0 { 0.0 } else { pnl / count as f64 },
        oracle_pnl_usd: oracle,
        oracle_regret_usd: regret,
        oracle_capture: if oracle.abs() <= f64::EPSILON {
            0.0
        } else {
            pnl / oracle
        },
        positive_event_fraction: if count == 0 {
            0.0
        } else {
            positive as f64 / count as f64
        },
    }
}

fn split_report(splits: &Splits, total: usize) -> SplitReport {
    let train = splits.train.end - splits.train.start;
    let validation = splits.validation.end - splits.validation.start;
    let holdout = splits.holdout.end - splits.holdout.start;
    SplitReport {
        total,
        train,
        validation,
        holdout,
        purged: total - train - validation - holdout,
        sessions: splits.session_count,
        purge_bars: splits.purge_bars,
    }
}

fn write_json<T: Serialize>(outdir: &Path, name: &str, value: &T) -> Result<()> {
    std::fs::create_dir_all(outdir)
        .with_context(|| format!("create output directory {}", outdir.display()))?;
    let path = outdir.join(name);
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .with_context(|| {
            format!(
                "create {} without clobbering an existing artifact",
                path.display()
            )
        })?;
    file.write_all(&serde_json::to_vec_pretty(value)?)?;
    file.write_all(b"\n")?;
    Ok(())
}

fn consistent_string(frame: &DataFrame, name: &str) -> Result<String> {
    let values = required_strings(frame, name)?;
    let first = values
        .first()
        .cloned()
        .ok_or_else(|| anyhow::anyhow!("{name} is empty"))?;
    if first.is_empty() || values.iter().any(|value| value != &first) {
        bail!("{name} is empty or inconsistent");
    }
    Ok(first)
}

fn required_strings(frame: &DataFrame, name: &str) -> Result<Vec<String>> {
    let column = frame
        .column(name)
        .with_context(|| format!("missing column {name}"))?;
    let series = column.as_materialized_series().cast(&DataType::String)?;
    series
        .str()?
        .into_iter()
        .enumerate()
        .map(|(index, value)| {
            value
                .map(ToOwned::to_owned)
                .ok_or_else(|| anyhow::anyhow!("{name} is null at row {index}"))
        })
        .collect()
}

fn required_f64(frame: &DataFrame, name: &str) -> Result<Vec<f64>> {
    let column = frame
        .column(name)
        .with_context(|| format!("missing column {name}"))?;
    let series = column.as_materialized_series().cast(&DataType::Float64)?;
    series
        .f64()?
        .into_iter()
        .enumerate()
        .map(|(index, value)| {
            let value = value.ok_or_else(|| anyhow::anyhow!("{name} is null at row {index}"))?;
            if !value.is_finite() {
                bail!("{name} is non-finite at row {index}");
            }
            Ok(value)
        })
        .collect()
}

fn required_i64(frame: &DataFrame, name: &str) -> Result<Vec<i64>> {
    let column = frame
        .column(name)
        .with_context(|| format!("missing column {name}"))?;
    let series = column.as_materialized_series().cast(&DataType::Int64)?;
    series
        .i64()?
        .into_iter()
        .enumerate()
        .map(|(index, value)| value.ok_or_else(|| anyhow::anyhow!("{name} is null at row {index}")))
        .collect()
}

fn required_usize(frame: &DataFrame, name: &str) -> Result<Vec<usize>> {
    required_i64(frame, name)?
        .into_iter()
        .enumerate()
        .map(|(index, value)| {
            usize::try_from(value).map_err(|_| anyhow::anyhow!("{name} is invalid at row {index}"))
        })
        .collect()
}

