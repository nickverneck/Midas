fn main() -> Result<()> {
    let args = Args::parse();
    if args.population < 2 && matches!(args.algorithm, Algorithm::Ga) {
        bail!("--population must be at least 2 for GA");
    }
    if !args.train_fraction.is_finite()
        || !args.validation_fraction.is_finite()
        || args.train_fraction <= 0.0
        || args.validation_fraction <= 0.0
        || args.train_fraction + args.validation_fraction >= 1.0
    {
        bail!("train/validation fractions must be positive and sum to less than 1");
    }
    if !args.learning_rate.is_finite()
        || args.learning_rate <= 0.0
        || !args.l2.is_finite()
        || args.l2 < 0.0
    {
        bail!("learning rate must be positive and l2 must be non-negative");
    }
    if args.explain_top == 0 {
        bail!("--explain-top must be positive");
    }
    if matches!(args.algorithm, Algorithm::Mlp) && args.hidden_size == 0 {
        bail!("--hidden-size must be positive for --algorithm mlp");
    }
    if !args.explain_event.is_empty() && !matches!(args.algorithm, Algorithm::Value) {
        bail!("--explain-event requires --algorithm value so the scores are action values");
    }
    if args.walk_forward_prior && !matches!(args.algorithm, Algorithm::Value) {
        bail!("--walk-forward-prior requires --algorithm value");
    }
    if args.walk_forward_prior
        && (args.orientation_prior_windows.is_empty()
            || args
                .orientation_prior_windows
                .iter()
                .any(|window| *window == 0)
            || args.orientation_prior_strengths.is_empty()
            || args
                .orientation_prior_strengths
                .iter()
                .any(|strength| !strength.is_finite() || *strength < 0.0))
    {
        bail!(
            "walk-forward orientation prior requires positive windows and finite non-negative strengths"
        );
    }
    if args.evaluate_policy.is_some() {
        if !matches!(args.algorithm, Algorithm::Value) {
            bail!("--evaluate-policy requires --algorithm value");
        }
        return evaluate_saved_policy(&args, args.evaluate_policy.as_deref().unwrap());
    }
    let feature_filter = expanded_feature_filter(args.feature_filter.as_deref(), args.regime_aware);
    let mut dataset = load_datasets(
        &args.input,
        feature_filter.as_deref(),
        args.allow_mixed_instruments,
    )?;
    if dataset.mixed_instruments && args.causal_history {
        bail!(
            "--causal-history is not supported for pooled instruments; history must be keyed by instrument and session before pooling"
        );
    }
    if args.causal_history {
        append_causal_history_features(&mut dataset)?;
    }
    if args.regime_aware {
        append_regime_features(&mut dataset)?;
    }
    let splits = split_rows(
        &dataset.rows,
        args.train_fraction,
        args.validation_fraction,
        args.purge_bars,
    )?;
    let (means, scales) = fit_scaler(&dataset.rows, &splits.train, dataset.feature_names.len());
    let reward_scales = fit_reward_scales(&dataset.rows, &splits.train, args.reward_normalization);
    let reward_scale = reported_reward_scale(&reward_scales, dataset.mixed_instruments);
    if matches!(args.algorithm, Algorithm::ReplayValue) {
        if dataset.mixed_instruments {
            bail!(
                "--algorithm replay-value currently requires one instrument; run one causal replay episode per instrument before pooling"
            );
        }
        return run_replay_value(
            &args,
            &dataset,
            &splits,
            &means,
            &scales,
            &reward_scales,
            reward_scale,
        );
    }
    let samples = normalize_rows(&dataset.rows, &means, &scales, &reward_scales);
    if matches!(args.algorithm, Algorithm::Advantage) {
        return run_advantage_diagnostic(&args, &dataset, &splits, &samples, reward_scale);
    }
    if matches!(args.algorithm, Algorithm::Mlp) {
        return run_mlp_diagnostic(&args, &dataset, &splits, &samples, reward_scale);
    }
    let result = match args.algorithm {
        Algorithm::Ga => train_ga(
            &samples,
            &splits,
            args.generations,
            args.population,
            args.seed,
            reward_scale,
            args.checkpoint_every,
            args.mutation_rate,
            args.mutation_step,
        )?,
        Algorithm::Rl => train_rl(
            &samples,
            &splits,
            args.epochs,
            args.seed,
            reward_scale,
            args.checkpoint_every,
            args.learning_rate,
            args.l2,
        )?,
        Algorithm::Value => train_value(
            &samples,
            &splits,
            args.epochs,
            reward_scale,
            args.checkpoint_every,
            args.learning_rate,
            args.l2,
        )?,
        Algorithm::ReplayValue | Algorithm::Advantage | Algorithm::Mlp => {
            unreachable!("diagnostic algorithms return above")
        }
    };

    let split_report = split_report(&splits, dataset.rows.len());
    let value_model = matches!(args.algorithm, Algorithm::Value);
    let selected_train = evaluate_policy(&samples, &splits.train, &result.policy, value_model);
    let selected_validation =
        evaluate_policy(&samples, &splits.validation, &result.policy, value_model);
    let learned = evaluate_policy(&samples, &splits.holdout, &result.policy, value_model);
    let fixed_normal = evaluate_fixed(&samples, &splits.holdout, 0);
    let fixed_invert = evaluate_fixed(&samples, &splits.holdout, 1);
    let calibration = if value_model {
        Some(calibration_report(
            &samples,
            &splits,
            &result.policy,
            &args.margin_thresholds,
            &args.prior_offsets,
            args.confidence_fallback,
        )?)
    } else {
        None
    };
    let walk_forward_prior = if args.walk_forward_prior {
        Some(orientation_prior_report(
            &dataset.rows,
            &samples,
            &splits,
            &result.policy,
            reward_scale,
            &args.orientation_prior_windows,
            &args.orientation_prior_strengths,
            args.orientation_prior_scope,
        )?)
    } else {
        None
    };
    let algorithm = match args.algorithm {
        Algorithm::Ga => "ga",
        Algorithm::Rl => "rl",
        Algorithm::Value => "value",
        Algorithm::ReplayValue | Algorithm::Advantage | Algorithm::Mlp => {
            unreachable!("diagnostic algorithms return above")
        }
    };
    let normalization = match args.reward_normalization {
        RewardNormalization::None => "none",
        RewardNormalization::TrainMeanAbs => "train-mean-abs",
    };
    let policy = PolicyArtifact {
        schema_version: "event-gate-policy-v1",
        warning: MODEL_WARNING,
        input: input_display(&args.input),
        algorithm: algorithm.to_string(),
        model_semantics: if value_model {
            "normalized_action_value_regression".to_string()
        } else {
            "action_logits".to_string()
        },
        seed: args.seed,
        actions: ["normal", "invert"],
        feature_names: dataset.feature_names.clone(),
        config_json: dataset.config_json.clone(),
        source_hash_sha256: dataset.source_hash.clone(),
        dataset_fingerprint_sha256: dataset.dataset_fingerprint.clone(),
        reward_normalization: normalization.to_string(),
        reward_scale_usd: reward_scale,
        reward_scales_usd_by_instrument: reward_scales.clone(),
        reward_definition: REWARD_DEFINITION,
        split: split_report.clone(),
        selected_iteration: result.selected_iteration,
        feature_means: means.clone(),
        feature_scales: scales.clone(),
        weights: result.policy.weights.clone(),
    };
    let metrics = MetricsArtifact {
        schema_version: "event-gate-metrics-v1",
        warning: MODEL_WARNING,
        input: input_display(&args.input),
        algorithm: algorithm.to_string(),
        seed: args.seed,
        actions: ["normal", "invert"],
        feature_names: dataset.feature_names.clone(),
        config_json: dataset.config_json,
        source_hash_sha256: dataset.source_hash,
        dataset_fingerprint_sha256: dataset.dataset_fingerprint,
        reward_normalization: normalization.to_string(),
        reward_scale_usd: reward_scale,
        reward_scales_usd_by_instrument: reward_scales,
        reward_definition: REWARD_DEFINITION,
        split: split_report,
        selected_iteration: result.selected_iteration,
        selected_train,
        selected_validation,
        fixed_normal,
        fixed_invert,
        learned,
        checkpoints: result.checkpoints,
        calibration,
        walk_forward_prior,
        leakage_check: "passed",
    };
    write_json(&args.outdir, "policy.json", &policy)?;
    write_json(&args.outdir, "metrics.json", &metrics)?;
    if !args.explain_event.is_empty() {
        let explanations = explain_events(
            &dataset.rows,
            &dataset.feature_names,
            &means,
            &scales,
            reward_scale,
            &result.policy,
            &args.explain_event,
            args.explain_top,
        )?;
        write_json(&args.outdir, "explanations.json", &explanations)?;
    }
    println!("{}", serde_json::to_string_pretty(&metrics)?);
    Ok(())
}

fn load_dataset(path: &Path, feature_filter: Option<&[String]>) -> Result<Dataset> {
    let frame = ParquetReader::new(
        File::open(path).with_context(|| format!("open input {}", path.display()))?,
    )
    .finish()
    .with_context(|| format!("read input {}", path.display()))?;
    if frame.height() == 0 {
        bail!("input contains no event rows");
    }
    let schema = consistent_string(&frame, "schema_version")?;
    if schema != SUPERVISED_DATASET_SCHEMA {
        bail!("expected {SUPERVISED_DATASET_SCHEMA}, found {schema}");
    }
    let label_schema = consistent_string(&frame, "label_schema")?;
    if label_schema != SUPERVISED_LABEL_SCHEMA {
        bail!("expected {SUPERVISED_LABEL_SCHEMA}, found {label_schema}");
    }
    let config_json = consistent_string(&frame, "config_json")?;
    let config: SupervisedConfig =
        serde_json::from_str(&config_json).context("decode supervised config_json")?;
    config.validate().context("validate supervised config")?;
    if config.label_mode != LabelMode::NormalInvert {
        bail!("event gate requires label_mode normal-invert");
    }
    if consistent_string(&frame, "leakage_check")? != "passed" {
        bail!("input leakage_check is not passed");
    }
    if consistent_string(&frame, "pnl_currency")? != "USD" {
        bail!("input PnL currency must be USD");
    }
    let instrument_key = consistent_string(&frame, "instrument")?;
    if instrument_key.trim().is_empty() {
        bail!("input instrument metadata cannot be empty");
    }
    let feature_schema = consistent_string(&frame, "feature_schema")?;
    let full_feature_names = feature_schema
        .split(',')
        .map(str::trim)
        .filter(|name| !name.is_empty())
        .map(ToOwned::to_owned)
        .collect::<Vec<_>>();
    if full_feature_names.is_empty() || full_feature_names != config.feature_names() {
        bail!("feature_schema does not match the configured causal feature registry");
    }
    validate_dimensionless_registry(&config)?;
    let feature_names = if let Some(requested) = feature_filter {
        if requested.is_empty() {
            bail!("--feature-filter must contain at least one feature");
        }
        let mut selected = Vec::with_capacity(requested.len());
        for name in &full_feature_names {
            if requested.iter().any(|candidate| candidate == name) {
                selected.push(name.clone());
            }
        }
        let unknown = requested
            .iter()
            .filter(|requested_name| !full_feature_names.contains(requested_name))
            .collect::<Vec<_>>();
        if !unknown.is_empty() {
            bail!("--feature-filter contains unknown features: {unknown:?}");
        }
        if selected.is_empty() {
            bail!("--feature-filter selected no features");
        }
        selected
    } else {
        full_feature_names
    };
    reject_future_features(&feature_names)?;
    let event_ids = required_usize(&frame, "event_id")?;
    let timestamps = required_i64(&frame, "timestamp_ns")?;
    let rows = required_usize(&frame, "row_idx")?;
    let horizons = required_usize(&frame, "interval_end_row_idx")?;
    let sessions = required_strings(&frame, "session_id")?;
    // action_value_* contains the dynamic program's best future continuation
    // and must not be summed as a per-event reward. Derive isolated rewards
    // from the event's audit prices instead.
    let raw_directions = required_i64(&frame, "raw_direction")?;
    let decision_prices = required_f64(&frame, "decision_price")?;
    let interval_end_prices = required_f64(&frame, "interval_end_price")?;
    let columns = feature_names
        .iter()
        .map(|name| required_f64(&frame, name))
        .collect::<Result<Vec<_>>>()?;
    let count = frame.height();
    if [
        event_ids.len(),
        timestamps.len(),
        rows.len(),
        horizons.len(),
        sessions.len(),
        raw_directions.len(),
        decision_prices.len(),
        interval_end_prices.len(),
    ]
    .into_iter()
    .any(|length| length != count)
        || columns.iter().any(|column| column.len() != count)
    {
        bail!("input columns do not have a common row count");
    }
    if timestamps.windows(2).any(|w| w[1] <= w[0]) {
        bail!("timestamp_ns must be strictly increasing");
    }
    if rows.windows(2).any(|w| w[1] <= w[0]) {
        bail!("row_idx must be strictly increasing");
    }
    let mut output = Vec::with_capacity(count);
    for index in 0..count {
        if sessions[index].is_empty() {
            bail!("session_id is empty at row {index}");
        }
        if horizons[index] <= rows[index] {
            bail!("interval_end_row_idx must be after row_idx at row {index}");
        }
        let raw_direction = i8::try_from(raw_directions[index])
            .with_context(|| format!("raw_direction is outside i8 range at row {index}"))?;
        if !matches!(raw_direction, -1 | 1) {
            bail!("raw_direction must be -1 or 1 at row {index}");
        }
        let delta = interval_end_prices[index] - decision_prices[index];
        let normal_reward =
            raw_direction as f64 * delta * config.contract_multiplier - config.round_trip_cost;
        let invert_reward =
            -(raw_direction as f64) * delta * config.contract_multiplier - config.round_trip_cost;
        let features = columns
            .iter()
            .map(|column| column[index])
            .collect::<Vec<_>>();
        if features.iter().any(|value| !value.is_finite()) {
            bail!("non-finite causal feature at row {index}");
        }
        output.push(Row {
            event_id: event_ids[index],
            timestamp_ns: timestamps[index],
            row_idx: rows[index],
            horizon_row_idx: horizons[index],
            session_id: sessions[index].clone(),
            instrument_key: instrument_key.clone(),
            raw_direction,
            decision_price: decision_prices[index],
            interval_end_price: interval_end_prices[index],
            contract_multiplier: config.contract_multiplier,
            round_trip_cost: config.round_trip_cost,
            raw_features: features,
            rewards: [normal_reward, invert_reward],
        });
    }
    Ok(Dataset {
        feature_names,
        rows: output,
        config_json,
        source_hash: consistent_string(&frame, "source_hash_sha256")?,
        dataset_fingerprint: consistent_string(&frame, "dataset_fingerprint_sha256")?,
        mixed_instruments: false,
    })
}

fn load_datasets(
    paths: &[PathBuf],
    feature_filter: Option<&[String]>,
    allow_mixed_instruments: bool,
) -> Result<Dataset> {
    if paths.is_empty() {
        bail!("at least one input parquet is required");
    }
    let mut datasets = paths
        .iter()
        .map(|path| load_dataset(path, feature_filter).map(|dataset| (path, dataset)))
        .collect::<Result<Vec<_>>>()?;
    let first_feature_names = datasets[0].1.feature_names.clone();
    let first_config_json = datasets[0].1.config_json.clone();
    let mut rows = Vec::new();
    let mut row_offset = 0usize;
    let mut previous_timestamp = None;
    let mut source_hashes = Vec::with_capacity(datasets.len());
    let mut fingerprints = Vec::with_capacity(datasets.len());
    let mut instrument_keys = std::collections::BTreeSet::new();
    for (path, dataset) in datasets.drain(..) {
        if dataset.feature_names != first_feature_names {
            bail!(
                "input {} has a different feature registry; all inputs must use the same config",
                path.display()
            );
        }
        if dataset.config_json != first_config_json
            && (!allow_mixed_instruments
                || !compatible_mixed_config(&first_config_json, &dataset.config_json)?)
        {
            bail!(
                "input {} has a different config_json; use --allow-mixed-instruments only for the same causal registry with instrument-specific multiplier/cost metadata",
                path.display()
            );
        }
        if !allow_mixed_instruments {
            if let (Some(previous), Some(current)) = (previous_timestamp, dataset.rows.first()) {
                if current.timestamp_ns <= previous {
                    bail!(
                        "inputs must be supplied in strict chronological order; {} begins at {} after {}",
                        path.display(),
                        current.timestamp_ns,
                        previous
                    );
                }
            }
        }
        instrument_keys.insert(
            dataset
                .rows
                .first()
                .map(|row| row.instrument_key.clone())
                .unwrap_or_else(|| "UNKNOWN".to_string()),
        );
        let session_prefix = if allow_mixed_instruments {
            None
        } else {
            Some(path.display().to_string())
        };
        for mut row in dataset.rows {
            row.event_id = row
                .event_id
                .checked_add(row_offset)
                .ok_or_else(|| anyhow::anyhow!("event ID overflow while merging inputs"))?;
            row.row_idx = row
                .row_idx
                .checked_add(row_offset)
                .ok_or_else(|| anyhow::anyhow!("row index overflow while merging inputs"))?;
            row.horizon_row_idx = row.horizon_row_idx.checked_add(row_offset).ok_or_else(|| {
                anyhow::anyhow!("horizon row index overflow while merging inputs")
            })?;
            if let Some(prefix) = &session_prefix {
                row.session_id = format!("{prefix}::{}", row.session_id);
            }
            previous_timestamp = Some(row.timestamp_ns);
            rows.push(row);
        }
        row_offset = rows
            .last()
            .map(|row| row.row_idx.saturating_add(1))
            .unwrap_or(row_offset);
        source_hashes.push(dataset.source_hash);
        fingerprints.push(dataset.dataset_fingerprint);
    }
    let mixed_instruments = allow_mixed_instruments && instrument_keys.len() > 1;
    if mixed_instruments {
        // Use one contiguous pooled session per calendar session. Events from
        // the two instruments may share timestamps, so strict input ordering
        // is intentionally relaxed only in this explicit mode.
        rows.sort_by(|left, right| {
            left.timestamp_ns
                .cmp(&right.timestamp_ns)
                .then_with(|| left.instrument_key.cmp(&right.instrument_key))
        });
        let base_timestamp = rows
            .first()
            .map(|row| row.timestamp_ns)
            .ok_or_else(|| anyhow::anyhow!("mixed input contains no rows"))?;
        for (index, row) in rows.iter_mut().enumerate() {
            let original_delta = row.horizon_row_idx.saturating_sub(row.row_idx);
            let minute_index =
                row.timestamp_ns.saturating_sub(base_timestamp).max(0) / 60_000_000_000;
            row.event_id = index;
            row.row_idx = usize::try_from(minute_index).unwrap_or(index);
            row.horizon_row_idx = row.row_idx.saturating_add(original_delta.max(1));
            row.session_id = row
                .session_id
                .rsplit("::")
                .next()
                .unwrap_or(&row.session_id)
                .to_string();
        }
    }
    Ok(Dataset {
        feature_names: first_feature_names,
        rows,
        config_json: first_config_json,
        source_hash: format!("multi:{}", source_hashes.join(",")),
        dataset_fingerprint: format!("multi:{}", fingerprints.join(",")),
        mixed_instruments,
    })
}

fn compatible_mixed_config(first: &str, other: &str) -> Result<bool> {
    let mut first: serde_json::Value =
        serde_json::from_str(first).context("decode first mixed config")?;
    let mut other: serde_json::Value =
        serde_json::from_str(other).context("decode mixed input config")?;
    for value in [&mut first, &mut other] {
        if let Some(object) = value.as_object_mut() {
            object.remove("contract_multiplier");
            object.remove("round_trip_cost");
        }
    }
    Ok(first == other)
}

fn append_causal_history_features(dataset: &mut Dataset) -> Result<()> {
    const HISTORY_NAMES: [&str; 7] = [
        "settled_history_count",
        "bars_since_last_settled_event",
        "settled_history_advantage_last",
        "settled_history_advantage_5",
        "settled_history_advantage_20",
        "settled_history_normal_win_rate_20",
        "settled_history_invert_win_rate_20",
    ];
    if dataset
        .feature_names
        .iter()
        .any(|name| HISTORY_NAMES.contains(&name.as_str()))
    {
        bail!("causal history features are already present");
    }
    let config: SupervisedConfig =
        serde_json::from_str(&dataset.config_json).context("decode config for causal history")?;
    if !config.contract_multiplier.is_finite() || config.contract_multiplier <= 0.0 {
        bail!("contract multiplier must be positive for causal history features");
    }

    // Compute additions separately so the values for the current event cannot
    // be observed while the source rows are being traversed. Only earlier
    // events whose interval has ended by the current crossover row qualify.
    let mut additions = vec![Vec::<f64>::new(); dataset.rows.len()];
    let mut session_start = 0;
    while session_start < dataset.rows.len() {
        let session_id = dataset.rows[session_start].session_id.clone();
        let session_end = dataset.rows[session_start..]
            .iter()
            .position(|row| row.session_id != session_id)
            .map(|offset| session_start + offset)
            .unwrap_or(dataset.rows.len());
        for index in session_start..session_end {
            let current_row_idx = dataset.rows[index].row_idx;
            let settled = (session_start..index)
                .filter(|previous| dataset.rows[*previous].horizon_row_idx <= current_row_idx)
                .collect::<Vec<_>>();
            let advantage = |previous: usize| {
                // Normalize with the prior event's own execution price. The
                // current event's decision_price is the next-bar open and is
                // not known at the current crossover close.
                let denominator = (dataset.rows[previous].decision_price.abs()
                    * config.contract_multiplier)
                    .max(1.0);
                (dataset.rows[previous].rewards[0] - dataset.rows[previous].rewards[1])
                    / (2.0 * denominator)
            };
            let mean_advantage = |indices: &[usize]| {
                if indices.is_empty() {
                    0.0
                } else {
                    indices
                        .iter()
                        .map(|previous| advantage(*previous))
                        .sum::<f64>()
                        / indices.len() as f64
                }
            };
            let recent_5_start = settled.len().saturating_sub(5);
            let recent_20_start = settled.len().saturating_sub(20);
            let recent_5 = &settled[recent_5_start..];
            let recent_20 = &settled[recent_20_start..];
            let normal_wins = recent_20
                .iter()
                .filter(|previous| dataset.rows[**previous].rewards[0] > 0.0)
                .count();
            let invert_wins = recent_20
                .iter()
                .filter(|previous| dataset.rows[**previous].rewards[1] > 0.0)
                .count();
            let bars_since_last = settled
                .last()
                .map(|previous| {
                    current_row_idx.saturating_sub(dataset.rows[*previous].horizon_row_idx) as f64
                })
                .unwrap_or(0.0);
            additions[index] = vec![
                settled.len() as f64,
                bars_since_last,
                settled
                    .last()
                    .map(|previous| advantage(*previous))
                    .unwrap_or(0.0),
                mean_advantage(recent_5),
                mean_advantage(recent_20),
                if recent_20.is_empty() {
                    0.0
                } else {
                    normal_wins as f64 / recent_20.len() as f64
                },
                if recent_20.is_empty() {
                    0.0
                } else {
                    invert_wins as f64 / recent_20.len() as f64
                },
            ];
        }
        session_start = session_end;
    }
    for (row, values) in dataset.rows.iter_mut().zip(additions) {
        row.raw_features.extend(values);
    }
    dataset
        .feature_names
        .extend(HISTORY_NAMES.into_iter().map(str::to_string));
    Ok(())
}

fn input_display(paths: &[PathBuf]) -> String {
    paths
        .iter()
        .map(|path| path.display().to_string())
        .collect::<Vec<_>>()
        .join(",")
}

