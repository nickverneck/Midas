#[derive(Debug, Clone, Copy, ValueEnum)]
enum Algorithm {
    Ga,
    Rl,
    Value,
    /// Position-conditioned action-value regression evaluated by sequential event replay.
    ReplayValue,
    /// One-dimensional normal-minus-invert advantage regression.
    Advantage,
    /// Small tanh MLP for the one-dimensional advantage target.
    Mlp,
}

