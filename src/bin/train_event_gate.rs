#[derive(Debug, Clone)]
struct Policy {
    weights: Vec<Vec<f64>>,
}

impl Policy {
    fn zero(feature_count: usize) -> Self {
        Self {
            weights: vec![vec![0.0; feature_count + 1]; 2],
        }
    }

    fn random(feature_count: usize, rng: &mut StdRng, scale: f64) -> Self {
        let mut policy = Self::zero(feature_count);
        for row in &mut policy.weights {
            for weight in row {
                *weight = rng.gen_range(-scale..scale);
            }
        }
        policy
    }

    fn scores(&self, features: &[f64]) -> [f64; 2] {
        [
            self.weights[0]
                .iter()
                .zip(features)
                .map(|(w, x)| w * x)
                .sum(),
            self.weights[1]
                .iter()
                .zip(features)
                .map(|(w, x)| w * x)
                .sum(),
        ]
    }

    fn probabilities(&self, features: &[f64]) -> [f64; 2] {
        let logits = self.scores(features);
        let max_logit = logits[0].max(logits[1]);
        let mut values = [(logits[0] - max_logit).exp(), (logits[1] - max_logit).exp()];
        let normalizer = values[0] + values[1];
        if !normalizer.is_finite() || normalizer <= f64::EPSILON {
            values = [0.5, 0.5];
        } else {
            values[0] /= normalizer;
            values[1] /= normalizer;
        }
        values
    }

    fn choose(&self, features: &[f64]) -> usize {
        let probabilities = self.probabilities(features);
        if probabilities[1] > probabilities[0] {
            1
        } else {
            0
        }
    }

    /// Choose the larger direct action-value estimate. Value-regression models
    /// must not pass their outputs through softmax: the magnitude and margin
    /// are part of the model's explanation and confidence signal.
    fn choose_value(&self, features: &[f64]) -> usize {
        let values = self.scores(features);
        if values[1] > values[0] { 1 } else { 0 }
    }

    fn value_estimates(&self, features: &[f64]) -> [f64; 2] {
        self.scores(features)
    }

    fn mutate(&mut self, rng: &mut StdRng, rate: f64, step: f64) {
        let mut changed = false;
        for row in &mut self.weights {
            for weight in row {
                if rng.gen_bool(rate.clamp(0.0, 1.0)) {
                    *weight = (*weight + rng.gen_range(-step..step)).clamp(-20.0, 20.0);
                    changed = true;
                }
            }
        }
        if !changed {
            let row = rng.gen_range(0..2);
            let col = rng.gen_range(0..self.weights[row].len());
            self.weights[row][col] =
                (self.weights[row][col] + rng.gen_range(-step..step)).clamp(-20.0, 20.0);
        }
    }
}

