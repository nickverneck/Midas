//! Train small normal/invert policies directly on the first-party
//! `supervised-event-v1` artifact.
//!
//! This is deliberately an event-level fixed-horizon diagnostic.  It is a
//! useful apples-to-apples GA/RL comparison for the supervised classifier,
//! but it is not a sequential Trader replay: action_value_* columns are
//! future labels and are never included in the feature vector.

